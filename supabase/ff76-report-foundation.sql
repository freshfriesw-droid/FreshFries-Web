-- FF76 foundation (already installed in project). Idempotent, non-destructive.
CREATE TABLE IF NOT EXISTS public.ff76_driver_work_sessions(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 driver_id uuid NOT NULL REFERENCES public.ff_drivers(id),
 checked_in_at timestamptz NOT NULL,
 checked_out_at timestamptz,
 source text NOT NULL DEFAULT 'presence_trigger',
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT ff76_work_dates CHECK(checked_out_at IS NULL OR checked_out_at>=checked_in_at)
);
CREATE INDEX IF NOT EXISTS ff76_work_driver_period_idx ON public.ff76_driver_work_sessions(driver_id,checked_in_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ff76_work_driver_start_uniq ON public.ff76_driver_work_sessions(driver_id,checked_in_at);
ALTER TABLE public.ff76_driver_work_sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ff76_driver_work_sessions FROM anon,authenticated;
REVOKE ALL ON SEQUENCE public.ff76_driver_work_sessions_id_seq FROM anon,authenticated;

CREATE OR REPLACE FUNCTION public.ff76_capture_driver_presence()
RETURNS trigger LANGUAGE plpgsql SET search_path TO '' AS $body$
BEGIN
 IF NEW.checked_in_at IS NOT NULL AND (TG_OP='INSERT' OR NEW.checked_in_at IS DISTINCT FROM OLD.checked_in_at) THEN
  UPDATE public.ff76_driver_work_sessions SET checked_out_at=NEW.checked_in_at
   WHERE driver_id=NEW.driver_id AND checked_out_at IS NULL AND checked_in_at<=NEW.checked_in_at;
  INSERT INTO public.ff76_driver_work_sessions(driver_id,checked_in_at,checked_out_at)
   VALUES(NEW.driver_id,NEW.checked_in_at,CASE WHEN NEW.checked_out_at IS NOT NULL
    AND NEW.checked_out_at>=NEW.checked_in_at THEN NEW.checked_out_at ELSE NULL END)
  ON CONFLICT(driver_id,checked_in_at) DO UPDATE SET checked_out_at=excluded.checked_out_at;
 ELSIF NEW.checked_out_at IS NOT NULL AND
  (TG_OP='INSERT' OR NEW.checked_out_at IS DISTINCT FROM OLD.checked_out_at) THEN
  UPDATE public.ff76_driver_work_sessions SET checked_out_at=NEW.checked_out_at
   WHERE driver_id=NEW.driver_id AND checked_out_at IS NULL AND checked_in_at<=NEW.checked_out_at;
 END IF;
 RETURN NEW;
END $body$;
DROP TRIGGER IF EXISTS ff76_presence_sessions_trigger ON public.ff38_driver_presence;
CREATE TRIGGER ff76_presence_sessions_trigger AFTER INSERT OR UPDATE OF checked_in_at,checked_out_at
 ON public.ff38_driver_presence FOR EACH ROW EXECUTE FUNCTION public.ff76_capture_driver_presence();
REVOKE ALL ON FUNCTION public.ff76_capture_driver_presence() FROM PUBLIC,anon,authenticated;

CREATE TABLE IF NOT EXISTS public.ff76_report_approvals(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 report_day date NOT NULL,
 scope_key text NOT NULL,
 branch_id uuid REFERENCES public.ff_branches(id),
 manager_notes text NOT NULL DEFAULT '',
 manager_name text NOT NULL DEFAULT '',
 approved_by uuid NOT NULL REFERENCES public.ff_profiles(user_id),
 approved_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(report_day,scope_key),
 CONSTRAINT ff76_notes_len CHECK(length(manager_notes)<=3000)
);
ALTER TABLE public.ff76_report_approvals ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ff76_report_approvals FROM anon,authenticated;
CREATE OR REPLACE FUNCTION public.ff76_report_approval_save(p_day date,p_branch uuid,p_notes text,p_manager_name text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $body$
DECLARE v_uid uuid:=auth.uid();v_record public.ff76_report_approvals;
BEGIN
 IF v_uid IS NULL OR NOT EXISTS(SELECT 1 FROM public.ff_profiles WHERE user_id=v_uid AND role='manager' AND active)
 THEN RAISE EXCEPTION 'اعتماد التقرير للمدير فقط' USING ERRCODE='42501'; END IF;
 IF p_day>public.ff_business_date(now()) OR p_day<date '2020-01-01'
 THEN RAISE EXCEPTION 'تاريخ الاعتماد غير صالح'; END IF;
 IF length(coalesce(p_notes,''))>3000 OR length(coalesce(p_manager_name,''))>120
 THEN RAISE EXCEPTION 'الملاحظات أو الاسم تجاوزا الحد'; END IF;
 IF p_branch IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.ff_branches WHERE id=p_branch)
 THEN RAISE EXCEPTION 'الفرع غير صحيح'; END IF;
 INSERT INTO public.ff76_report_approvals(report_day,scope_key,branch_id,manager_notes,manager_name,approved_by,approved_at)
 VALUES(p_day,coalesce(p_branch::text,'all'),p_branch,coalesce(p_notes,''),coalesce(nullif(trim(p_manager_name),''),(SELECT display_name FROM public.ff_profiles WHERE user_id=v_uid)),v_uid,now())
 ON CONFLICT(report_day,scope_key) DO UPDATE SET manager_notes=excluded.manager_notes,
 manager_name=excluded.manager_name,approved_by=excluded.approved_by,approved_at=excluded.approved_at
 RETURNING * INTO v_record;
 RETURN jsonb_build_object('approved',true,'manager_name',v_record.manager_name,
   'approved_at',v_record.approved_at,'notes',v_record.manager_notes);
END $body$;
REVOKE ALL ON FUNCTION public.ff76_report_approval_save(date,uuid,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.ff76_report_approval_save(date,uuid,text,text) TO authenticated;