BEGIN;
DO $qa$
DECLARE u uuid:=gen_random_uuid(); m uuid:=gen_random_uuid(); customer uuid:=gen_random_uuid(); old_sid uuid:=gen_random_uuid(); new_sid uuid:=gen_random_uuid(); csid uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); n int; checks int:=0;
BEGIN
 INSERT INTO auth.users(id) VALUES(u),(m),(customer);
 INSERT INTO public.ff_profiles(user_id,display_name,role,active) VALUES(u,'QA STEP12 staff lifecycle','cashier',true),(m,'QA STEP12 manager lifecycle','manager',true);
 INSERT INTO public.ff_branches(id,code,name) VALUES(b,'qa-session-life-'||b,'QA session lifecycle');
 INSERT INTO public.ff_user_branches(user_id,branch_id) VALUES(u,b);
 INSERT INTO auth.sessions(id,user_id,created_at,updated_at) VALUES(old_sid,u,clock_timestamp()-interval '1 hour',clock_timestamp()),(csid,customer,clock_timestamp()-interval '1 hour',clock_timestamp());
 PERFORM set_config('request.jwt.claim.sub',u::text,true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',u,'role','authenticated','session_id',old_sid)::text,true);
 SET LOCAL ROLE authenticated;
 IF NOT public.ff_step12_session_valid() THEN RAISE EXCEPTION 'Baseline session invalid';END IF;
 PERFORM public.ff_step12_assert_session();checks:=checks+1;
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub',m::text,true);
 PERFORM set_config('request.jwt.claims','',true);
 SET LOCAL ROLE authenticated;
 PERFORM public.ff38_admin_staff_set_active(u,false);
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub',u::text,true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',u,'role','authenticated','session_id',old_sid)::text,true);
 SET LOCAL ROLE authenticated;
 IF public.ff_step12_session_valid() THEN RAISE EXCEPTION 'Suspended employee session accepted';END IF;
 BEGIN PERFORM public.ff_step12_assert_session(); RAISE EXCEPTION 'Suspended API session accepted' USING ERRCODE='ZQA12';EXCEPTION WHEN SQLSTATE 'PT401' THEN NULL;END;
 checks:=checks+1;
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub',m::text,true);
 PERFORM set_config('request.jwt.claims','',true);
 SET LOCAL ROLE authenticated;
 PERFORM public.ff38_admin_staff_set_active(u,true);
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub',u::text,true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',u,'role','authenticated','session_id',old_sid)::text,true);
 SET LOCAL ROLE authenticated;
 IF public.ff_step12_session_valid() THEN RAISE EXCEPTION 'Old session revived';END IF;
 BEGIN PERFORM public.ff_step12_assert_session();RAISE EXCEPTION 'Reactivated old API session accepted' USING ERRCODE='ZQA12';EXCEPTION WHEN SQLSTATE 'PT401' THEN NULL;END;checks:=checks+1;
 SELECT count(*) INTO n FROM public.ff_branches WHERE id=b;
 IF n<>0 THEN RAISE EXCEPTION 'Old session retained RLS branch access';END IF;checks:=checks+1;
 RESET ROLE;
 INSERT INTO auth.sessions(id,user_id,created_at,updated_at) VALUES(new_sid,u,clock_timestamp(),clock_timestamp());
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',u,'role','authenticated','session_id',new_sid)::text,true);
 SET LOCAL ROLE authenticated;
 IF NOT public.ff_step12_session_valid() THEN RAISE EXCEPTION 'Fresh session denied';END IF;
 PERFORM public.ff_step12_assert_session();SELECT count(*) INTO n FROM public.ff_branches WHERE id=b;
 IF n<>1 THEN RAISE EXCEPTION 'Fresh session RLS broken';END IF;checks:=checks+1;
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub',customer::text,true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',customer,'role','authenticated','session_id',csid)::text,true);
 SET LOCAL ROLE authenticated;
 IF NOT public.ff_step12_session_valid() THEN RAISE EXCEPTION 'Customer session denied';END IF;checks:=checks+1;
 RESET ROLE;
 IF (SELECT count(*) FROM auth.sessions WHERE id IN(old_sid,new_sid,csid))<>3 THEN RAISE EXCEPTION 'Fixture sessions deleted';END IF;checks:=checks+1;
 IF has_table_privilege('authenticated','ff_private.step12_staff_session_cutoffs','SELECT') OR has_table_privilege('anon','ff_private.step12_staff_session_cutoffs','SELECT') THEN RAISE EXCEPTION 'Cutoff readable by client';END IF;checks:=checks+1;
 IF checks<>8 THEN RAISE EXCEPTION 'Incomplete lifecycle checks';END IF;
END $qa$;
SELECT 'PASS STEP12 lifecycle: 8 assertions; suspension and reactivation invalidate prior session, fresh and customer sessions preserved, RLS denial and no session deletion' result;
