-- Fresh Fries LUXE / Kitchen Burger Section / 2026-11-23
-- Fully additive workflow; does not alter ff_orders or existing cashier workflows.

ALTER TABLE public.ff_profiles DROP CONSTRAINT IF EXISTS ff_profiles_role_check;
ALTER TABLE public.ff_profiles ADD CONSTRAINT ff_profiles_role_check
CHECK (role = ANY(ARRAY['manager','supervisor','customer_service','cashier','driver','assembly','burger_kitchen']));

CREATE TABLE IF NOT EXISTS public.ff_burger_tickets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  client_token uuid NOT NULL UNIQUE,
  branch_id uuid NOT NULL REFERENCES public.ff_branches(id),
  order_kind text NOT NULL CHECK (order_kind IN ('local','delivery')),
  delivery_order_id uuid REFERENCES public.ff_orders(id) ON DELETE CASCADE,
  invoice_ref text NOT NULL CHECK (length(btrim(invoice_ref)) BETWEEN 1 AND 80),
  cashier_id uuid NOT NULL REFERENCES public.ff_profiles(user_id),
  cashier_name text NOT NULL,
  kitchen_id uuid REFERENCES public.ff_profiles(user_id),
  kitchen_name text,
  items jsonb NOT NULL CHECK (jsonb_typeof(items)='array' AND jsonb_array_length(items) BETWEEN 1 AND 20),
  notes text NOT NULL DEFAULT '' CHECK (length(notes)<=1000),
  status text NOT NULL DEFAULT 'sent' CHECK (status IN ('sent','preparing','ready','acknowledged')),
  sent_at timestamptz NOT NULL DEFAULT now(),
  accepted_at timestamptz,
  ready_at timestamptz,
  acknowledged_at timestamptz,
  acknowledged_by uuid REFERENCES public.ff_profiles(user_id),
  CONSTRAINT ff_burger_kind_order_check CHECK (
   (order_kind='local' AND delivery_order_id IS NULL)
   OR (order_kind='delivery' AND delivery_order_id IS NOT NULL)),
  CONSTRAINT ff_burger_time_check CHECK (
   (status='sent' AND accepted_at IS NULL AND ready_at IS NULL)
   OR (status='preparing' AND accepted_at IS NOT NULL AND ready_at IS NULL)
   OR (status IN ('ready','acknowledged') AND accepted_at IS NOT NULL AND ready_at IS NOT NULL))
);

-- A deliberate manager reset of delivery orders may delete linked burger tickets;
-- it must never be blocked by this module. Local burger tickets are independent.
CREATE INDEX IF NOT EXISTS ff_burger_branch_status_idx
 ON public.ff_burger_tickets(branch_id,status,sent_at DESC);
CREATE INDEX IF NOT EXISTS ff_burger_delivery_link_idx
 ON public.ff_burger_tickets(delivery_order_id) WHERE delivery_order_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.ff_burger_ticket_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id uuid NOT NULL REFERENCES public.ff_burger_tickets(id) ON DELETE CASCADE,
 actor_id uuid REFERENCES public.ff_profiles(user_id),
 previous_status text,
 next_status text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ff_burger_events_ticket_idx ON public.ff_burger_ticket_events(ticket_id,created_at DESC);

ALTER TABLE public.ff_burger_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ff_burger_ticket_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.ff_burger_tickets,public.ff_burger_ticket_events FROM PUBLIC,anon,authenticated;
GRANT SELECT ON TABLE public.ff_burger_tickets TO authenticated;
