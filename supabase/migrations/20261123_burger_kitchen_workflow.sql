CREATE OR REPLACE FUNCTION public.ff_burger_my_branch()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=''
AS $func$
DECLARE v_role text; v_branches jsonb;
BEGIN
 SELECT role INTO v_role FROM public.ff_profiles WHERE user_id=auth.uid() AND active;
 IF v_role NOT IN ('cashier','burger_kitchen') THEN
   RAISE EXCEPTION 'غير مصرح بواجهة البرجر' USING ERRCODE='42501'; END IF;
 SELECT coalesce(jsonb_agg(jsonb_build_object('id',b.id,'name',b.name,'code',b.code) ORDER BY b.name),'[]'::jsonb)
 INTO v_branches
 FROM public.ff_user_branches ub JOIN public.ff_branches b ON b.id=ub.branch_id
 WHERE ub.user_id=auth.uid() AND b.active;
 IF jsonb_array_length(v_branches)=0 THEN RAISE EXCEPTION 'الحساب غير مرتبط بفرع نشط' USING ERRCODE='42501'; END IF;
 IF v_role='burger_kitchen' AND jsonb_array_length(v_branches)<>1 THEN
   RAISE EXCEPTION 'يلزم تحديد فرع واحد فقط لحساب قسم البرجر' USING ERRCODE='42501'; END IF;
 RETURN jsonb_build_object('role',v_role,'branches',v_branches);
END $func$;

CREATE OR REPLACE FUNCTION public.ff_burger_menu()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=''
AS $func$
BEGIN
 PERFORM public.ff_burger_my_branch();
 RETURN coalesce((SELECT jsonb_agg(jsonb_build_object('id',i.id,'name',i.name) ORDER BY i.sort_order,i.name)
  FROM public.ff_menu_items i JOIN public.ff_menu_categories c ON c.id=i.category_id
  WHERE i.active AND c.active AND c.name ILIKE '%برجر%'),'[]'::jsonb);
END $func$;

CREATE OR REPLACE FUNCTION public.ff_burger_send(
 p_branch uuid, p_order_kind text, p_delivery_order uuid, p_invoice text,
 p_items jsonb, p_notes text, p_token uuid
) RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=''
AS $func$
DECLARE v_id uuid;v_name text;v_item jsonb;v_item_id uuid;v_qty integer;
 v_record record;v_checked jsonb:='[]'::jsonb;v_sum integer:=0;v_seen uuid[]:=ARRAY[]::uuid[];
BEGIN
 SELECT display_name INTO v_name FROM public.ff_profiles
  WHERE user_id=auth.uid() AND active=true AND role='cashier';
 IF v_name IS NULL THEN RAISE EXCEPTION 'إرسال أوامر البرجر للكاشير فقط' USING ERRCODE='42501';END IF;
 IF p_branch IS NULL OR NOT EXISTS (
  SELECT 1 FROM public.ff_user_branches ub JOIN public.ff_branches b ON b.id=ub.branch_id
  WHERE ub.user_id=auth.uid() AND ub.branch_id=p_branch AND b.active)
 THEN RAISE EXCEPTION 'الفرع غير مصرح به' USING ERRCODE='42501'; END IF;
 IF p_token IS NULL THEN RAISE EXCEPTION 'معرّف الإرسال مطلوب'; END IF;
 SELECT id INTO v_id FROM public.ff_burger_tickets WHERE client_token=p_token AND cashier_id=auth.uid();
 IF v_id IS NOT NULL THEN RETURN jsonb_build_object('saved',true,'id',v_id,'duplicate',true); END IF;
 IF p_order_kind NOT IN ('local','delivery') THEN RAISE EXCEPTION 'نوع الطلب غير صالح'; END IF;
 IF length(btrim(coalesce(p_invoice,''))) NOT BETWEEN 1 AND 80
 THEN RAISE EXCEPTION 'اكتب رقم فاتورة الكاشير المرتبطة بالطلب (80 حرفًا كحد أقصى)';END IF;
 IF length(coalesce(p_notes,''))>1000 THEN RAISE EXCEPTION 'الملاحظات طويلة جدًا'; END IF;
 IF p_order_kind='local' AND p_delivery_order IS NOT NULL THEN
  RAISE EXCEPTION 'الطلب المحلي لا يحتاج رقم طلب توصيل';END IF;
 IF p_order_kind='delivery' AND NOT EXISTS (
   SELECT 1 FROM public.ff_orders o WHERE o.id=p_delivery_order AND o.branch_id=p_branch
   AND o.order_type='delivery' AND o.status NOT IN ('cancelled','canceled','closed')
   AND (NOT EXISTS(SELECT 1 FROM public.ff_luxe_cashier_staff_desks sd WHERE sd.user_id=auth.uid())
     OR NOT EXISTS(SELECT 1 FROM public.ff_luxe_cashier_order_desks od WHERE od.order_id=o.id)
     OR EXISTS(SELECT 1 FROM public.ff_luxe_cashier_staff_desks sd JOIN public.ff_luxe_cashier_order_desks od
      ON sd.desk_code=od.desk_code WHERE sd.user_id=auth.uid() AND od.order_id=o.id))
 ) THEN RAISE EXCEPTION 'اختر طلب توصيل تابع لفرعك ووجهة الكاشير المسموحة';END IF;
 IF p_items IS NULL OR jsonb_typeof(p_items)<>'array'
   OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 20 THEN
   RAISE EXCEPTION 'حدد صنف برجر واحدًا على الأقل';END IF;
 FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
 LOOP
   IF jsonb_typeof(v_item)<>'object' OR (v_item->>'id') IS NULL OR
      (v_item->>'qty') !~ '^[1-9][0-9]?$' THEN
      RAISE EXCEPTION 'كمية أو صنف البرجر غير صالح';END IF;
   v_item_id:=(v_item->>'id')::uuid;v_qty:=(v_item->>'qty')::integer;
   IF v_item_id=ANY(v_seen) THEN RAISE EXCEPTION 'الصنف مكرر، عدل الكمية في سطر واحد';END IF;
   v_seen:=array_append(v_seen,v_item_id);v_sum:=v_sum+v_qty;
   IF v_sum>100 THEN RAISE EXCEPTION 'الكمية الإجمالية أكبر من المسموح'; END IF;
   SELECT i.name INTO v_name FROM public.ff_menu_items i
      JOIN public.ff_menu_categories c ON c.id=i.category_id
      WHERE i.id=v_item_id AND i.active AND c.active AND c.name ILIKE '%برجر%';
   IF v_name IS NULL THEN RAISE EXCEPTION 'يوجد صنف غير فعال أو ليس من قسم البرجر';END IF;
   v_checked:=v_checked||jsonb_build_array(jsonb_build_object('id',v_item_id,'name',v_name,'qty',v_qty));
 END LOOP;
 SELECT display_name INTO v_name FROM public.ff_profiles WHERE user_id=auth.uid();
 INSERT INTO public.ff_burger_tickets
   (client_token,branch_id,order_kind,delivery_order_id,invoice_ref,cashier_id,cashier_name,items,notes)
 VALUES(p_token,p_branch,p_order_kind,p_delivery_order,btrim(p_invoice),auth.uid(),v_name,
   v_checked,btrim(coalesce(p_notes,'')))
 ON CONFLICT(client_token) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT id INTO v_id FROM public.ff_burger_tickets WHERE client_token=p_token AND cashier_id=auth.uid();
  IF v_id IS NULL THEN RAISE EXCEPTION 'معرّف إرسال مستخدم لحساب آخر';END IF;
 END IF;
 RETURN jsonb_build_object('saved',true,'id',v_id);
END $func$;

CREATE OR REPLACE FUNCTION public.ff_burger_list(p_limit integer DEFAULT 75)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=''
AS $func$
DECLARE v_role text;v_branches jsonb;
BEGIN
 SELECT role INTO v_role FROM public.ff_profiles WHERE user_id=auth.uid() AND active;
 IF v_role NOT IN ('cashier','burger_kitchen') THEN RAISE EXCEPTION 'غير مصرح' USING ERRCODE='42501'; END IF;
 RETURN coalesce((
 SELECT jsonb_agg(to_jsonb(s) ORDER BY s.sent_at DESC)
 FROM (SELECT t.id,t.branch_id,t.order_kind,t.delivery_order_id,t.invoice_ref,
   t.cashier_name,t.kitchen_id,t.kitchen_name,t.items,t.notes,t.status,t.sent_at,t.accepted_at,t.ready_at,
   t.acknowledged_at,b.name AS branch_name,
   CASE WHEN t.accepted_at IS NOT NULL AND t.ready_at IS NOT NULL THEN
    greatest(0,extract(epoch from(t.ready_at-t.accepted_at))::integer) ELSE NULL END AS prep_seconds
 FROM public.ff_burger_tickets t JOIN public.ff_branches b ON b.id=t.branch_id
 WHERE EXISTS(SELECT 1 FROM public.ff_user_branches ub WHERE ub.user_id=auth.uid() AND ub.branch_id=t.branch_id)
 ORDER BY CASE WHEN t.status IN ('sent','preparing','ready') THEN 0 ELSE 1 END,
   t.sent_at DESC LIMIT LEAST(GREATEST(coalesce(p_limit,75),1),150)
 ) s),'[]'::jsonb);
END $func$;

CREATE OR REPLACE FUNCTION public.ff_burger_transition(p_ticket uuid,p_action text)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=''
AS $func$
DECLARE v_role text;v_person text;v_row public.ff_burger_tickets%ROWTYPE;
BEGIN
 SELECT role,display_name INTO v_role,v_person FROM public.ff_profiles
 WHERE user_id=auth.uid() AND active;
 IF v_role NOT IN ('cashier','burger_kitchen') THEN
   RAISE EXCEPTION 'الدور غير مخول' USING ERRCODE='42501';END IF;
 SELECT * INTO v_row FROM public.ff_burger_tickets WHERE id=p_ticket FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'الطلب غير موجود';END IF;
 IF NOT EXISTS(SELECT 1 FROM public.ff_user_branches WHERE user_id=auth.uid() AND branch_id=v_row.branch_id)
 THEN RAISE EXCEPTION 'طلب يخص فرعًا آخر' USING ERRCODE='42501';END IF;
 IF p_action='receive' AND v_role='burger_kitchen' AND v_row.status='sent' THEN
  UPDATE public.ff_burger_tickets SET status='preparing',kitchen_id=auth.uid(),kitchen_name=v_person,
     accepted_at=clock_timestamp() WHERE id=p_ticket;
 ELSIF p_action='ready' AND v_role='burger_kitchen' AND v_row.status='preparing'
     AND v_row.kitchen_id=auth.uid() THEN
  UPDATE public.ff_burger_tickets SET status='ready',ready_at=clock_timestamp() WHERE id=p_ticket;
 ELSIF p_action='skip' AND v_role='cashier' AND v_row.status='ready' THEN
  UPDATE public.ff_burger_tickets SET status='acknowledged',acknowledged_at=clock_timestamp(),
     acknowledged_by=auth.uid() WHERE id=p_ticket;
 ELSE RAISE EXCEPTION 'المرحلة تغيرت أو العملية غير مصرح بها؛ حدث القائمة' USING ERRCODE='42501';
 END IF;
 RETURN jsonb_build_object('saved',true,'id',p_ticket,'action',p_action);
END $func$;

CREATE OR REPLACE FUNCTION ff_private.ff_burger_event_and_notify()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $func$
DECLARE v_kind text;v_message text;v_key text;
BEGIN
 IF TG_OP='INSERT' THEN
   v_kind:='sent';v_message:='طلب برجر جديد';v_key:='burger:sent:'||NEW.id::text;
 ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
   v_kind:=NEW.status;v_message:=CASE WHEN NEW.status='ready' THEN 'طلب البرجر جاهز للاستلام'
     WHEN NEW.status='preparing' THEN 'بدأ تحضير البرجر' ELSE 'تحديث حالة البرجر' END;
   v_key:='burger:'||NEW.status||':'||NEW.id::text;
 ELSE RETURN NEW;END IF;
 INSERT INTO public.ff_burger_ticket_events(ticket_id,actor_id,previous_status,next_status)
 VALUES(NEW.id,auth.uid(),CASE WHEN TG_OP='INSERT' THEN NULL ELSE OLD.status END,NEW.status);
 IF v_kind IN ('sent','ready') THEN
   INSERT INTO public.ff_push_jobs(user_id,order_id,event_key,kind,title,body)
   SELECT p.user_id,NEW.delivery_order_id,v_key,'employee_notice',
     CASE WHEN v_kind='sent' THEN '🍔 طلب جديد لقسم البرجر' ELSE '✅ البرجر جاهز للاستلام' END,
     'فاتورة #'||NEW.invoice_ref||' · '||v_message
   FROM public.ff_profiles p
   JOIN public.ff_user_branches ub ON ub.user_id=p.user_id AND ub.branch_id=NEW.branch_id
   WHERE p.active AND (
      (v_kind='sent' AND p.role='burger_kitchen') OR
      (v_kind='ready' AND p.role='cashier'))
   ON CONFLICT(user_id,event_key) DO NOTHING;
   BEGIN PERFORM ff_private.push_kick();
   EXCEPTION WHEN OTHERS THEN RAISE WARNING 'تعذر تعجيل إشعار البرجر: %',SQLERRM; END;
 END IF;
 RETURN NEW;
END $func$;
DROP TRIGGER IF EXISTS ff_burger_event_and_notify ON public.ff_burger_tickets;
CREATE TRIGGER ff_burger_event_and_notify
AFTER INSERT OR UPDATE OF status ON public.ff_burger_tickets
FOR EACH ROW EXECUTE FUNCTION ff_private.ff_burger_event_and_notify();

